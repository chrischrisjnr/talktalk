// Builds the front-end assets that come from IBM Carbon:
//   1. styles/carbon.scss      -> public/css/carbon.css   (Carbon components + themes)
//   2. selected Carbon icons   -> public/js/icons.js      (inline SVG, no network requests)
//
// The outputs are committed, so you only need this when changing the Carbon
// build or adding an icon:  npm run build

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as sass from 'sass';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

// ---- 1. Carbon CSS -------------------------------------------------------
const result = sass.compile(path.join(root, 'styles/carbon.scss'), {
  loadPaths: [path.join(root, 'node_modules')],
  style: 'compressed',
  quietDeps: true,
  silenceDeprecations: ['import', 'global-builtin'],
});
const banner = '/* IBM Carbon Design System (Apache-2.0) — slim build for talktalk */\n';
fs.writeFileSync(path.join(root, 'public/css/carbon.css'), banner + result.css);
console.log(`carbon.css  ${(result.css.length / 1024).toFixed(0)} KB`);

// ---- 2. Icons ------------------------------------------------------------
const ICONS = [
  'add', 'arrow--right', 'attachment', 'chat', 'checkmark', 'close', 'color-palette', 'document',
  'download', 'edit', 'erase', 'events', 'face--add', 'face--satisfied', 'forum', 'hashtag',
  'image', 'information', 'logout', 'menu', 'paint-brush', 'pen', 'search', 'send--alt', 'trash-can',
  'upload', 'user', 'user--avatar', 'volume--mute', 'volume--up', 'email', 'circle-dash',
];
const iconDir = path.join(root, 'node_modules/@carbon/icons/svg/32');
const icons = {};
for (const name of ICONS) {
  const svg = fs.readFileSync(path.join(iconDir, `${name}.svg`), 'utf8');
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)[1]
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/\s+id="[^"]*"/g, '')
    .replace(/\s+data-name="[^"]*"/g, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
  icons[name] = inner;
}
fs.writeFileSync(
  path.join(root, 'public/js/icons.js'),
  '// IBM Carbon icons (Apache-2.0), generated by scripts/build.mjs. 32×32 artboard.\n' +
    `window.ICONS = ${JSON.stringify(icons, null, 1)};\n`
);
console.log(`icons.js    ${ICONS.length} icons`);
